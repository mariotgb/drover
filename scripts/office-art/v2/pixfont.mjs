const glyph = (ch) => GLYPHS[ch] ?? GLYPHS[SAME[ch]] ?? GLYPHS[FOLD[ch]] ?? GLYPHS["?"]

export const FONT_HEIGHT = 5
export function measure(s) {
  let w = 0
  for (const ch of s.toUpperCase()) w += glyph(ch)[0].length + 1
  return Math.max(0, w - 1)
}
/** Draw text; returns the width. `scale` doubles pixels for signs. */
export function print(c, x, y, s, color, scale = 1) {
  let cx = x
  for (const ch of s.toUpperCase()) {
    const g = glyph(ch)
    g.forEach((row, j) => [...row].forEach((p, i) => { if (p === '#') c.rect(cx + i * scale, y + j * scale, scale, scale, color) }))
    cx += (g[0].length + 1) * scale
  }
  return cx - x - scale
}
/** Fit a name into `max` px: drop a shared prefix first (done by the caller), then ellipsis. */
export function fit(s, max) {
  if (measure(s) <= max) return s
  let t = s
  while (t.length > 1 && measure(t + '…') > max) t = t.slice(0, -1)
  return t + '…'
}
